test('submit, list, show, wait, cancel: the protocol from the host, with the worker played by hand', async () => {
  const w = makeWorld()
  const src = w.jobDir('t1-cache', { 'prompt.md': 'cache it\n', 'repos/app/README.md': 'hi\n' })
  const s = cli(w, 'submit', src)
  assert.equal(s.code, 0, s.stderr)
  assert.equal(s.stdout, 't1-cache\n')
  assert.ok(existsSync(join(src, 'prompt.md')), 'a copy; the source stays')
  assert.equal(readFileSync(join(w.dirs.queue, 't1-cache', 'repos', 'app', 'README.md'), 'utf8'), 'hi\n')
  assert.equal(cli(w, 'submit', src).code, 1, 'a name that exists is refused')
  assert.equal(cli(w, 'submit', src, '--name', '.hidden').code, 2, 'a dotted name would never be seen')
  assert.equal(cli(w, 'submit', src, '--name', 'a b').code, 2)
  assert.equal(cli(w, 'submit', join(w.dir, 'nowhere')).code, 2)

  const moved = w.jobDir('t2', { 'run.sh': 'echo hi\n' })
  assert.equal(cli(w, 'submit', moved, '--move', '--timeout', '45m').stdout, 't2\n')
  assert.ok(!existsSync(moved), '--move takes the directory')
  assert.deepEqual(JSON.parse(readFileSync(join(w.dirs.queue, 't2', 'job.json'), 'utf8')), { timeout: '45m' })
  assert.equal(cli(w, 'submit', w.jobDir('t3', { 'job.json': '{"agent":"claude"}\n' }), '--timeout', '1h').code, 0)
  assert.deepEqual(JSON.parse(readFileSync(join(w.dirs.queue, 't3', 'job.json'), 'utf8')), { agent: 'claude', timeout: '1h' }, 'the timeout joins what job.json already says')
  assert.equal(cli(w, 'submit', src, '--name', 't4', '--timeout', '90').code, 2, 'the worker wants a unit')
  assert.ok(!existsSync(join(w.dirs.queue, 't4')) && !existsSync(join(w.dirs.queue, '.tmp-t4')), 'nothing left behind when refused')

  let list = cli(w, 'list')
  assert.match(list.stdout, /^t1-cache {2}queued {4}queued/m)
  assert.match(list.stdout, /^t2 {8}queued {4}queued/m)
  assert.deepEqual(JSON.parse(cli(w, 'list', '--json').stdout).map((j: { name: string; place: string }) => [j.name, j.place]), [['t1-cache', 'queued'], ['t2', 'queued'], ['t3', 'queued']])

  const notDone = cli(w, 'wait', 't1-cache', '--timeout', '300')
  assert.equal(notDone.code, 2, 'wait\'s own timeout')
  assert.match(notDone.stderr, /not done after 300/)
  assert.equal(cli(w, 'wait', 't1-cache', '--timeout', 'soon').code, 2)

  w.claim('t1-cache')
  const running = cli(w, 'show', 't1-cache')
  assert.equal(running.code, 0, running.stderr)
  assert.match(running.stdout, /^place {5}running$/m)
  assert.match(running.stdout, /^worker {4}w1$/m)
  assert.match(cli(w, 'list').stdout, /^t1-cache {2}running {3}running +2026-09-25T10:00:00/m)

  assert.match(cli(w, 'cancel', 't1-cache').stdout, /Asked the worker to stop/)
  assert.ok(existsSync(join(w.dirs.running, 't1-cache', 'cancel')), 'a running job gets a cancel file')
  assert.match(cli(w, 'cancel', 't2').stdout, /Canceled t2; it never ran/)
  const t2 = JSON.parse(readFileSync(join(w.dirs.done, 't2', 'result.json'), 'utf8'))
  assert.equal(t2.status, 'canceled')
  assert.equal(t2.worker, 'heai-pod')
  assert.equal(cli(w, 'cancel', 't2').code, 1, 'already done')

  w.finish('t1-cache', { status: 'canceled', exit: -1, signal: 'TERMINATED' }, { stdout: 'line 1\nline 2\nline 3\n', stderr: 'oops\n' })
  const waited = cli(w, 'wait', 't1-cache')
  assert.equal(waited.code, 1, 'settled badly')
  assert.equal(waited.stdout, 'canceled\n')
  const shown = cli(w, 'show', 't1-cache', '--lines', '2')
  assert.match(shown.stdout, /^status {4}canceled$/m)
  assert.match(shown.stdout, /^signal {4}TERMINATED$/m)
  assert.match(shown.stdout, /^duration {2}1m31s$/m)
  assert.match(shown.stdout, /--- log\/stdout \(last 2 lines\)\nline 2\nline 3\n--- log\/stderr/)
  assert.ok(!/line 1/.test(shown.stdout))
  const shownJson = JSON.parse(cli(w, 'show', 't1-cache', '--json').stdout)
  assert.equal(shownJson.place, 'done')
  assert.equal(shownJson.result.status, 'canceled')
  assert.equal(shownJson.log.stderr, 'oops\n')

  w.claim('t3')
  w.finish('t3', {})
  const ok = cli(w, 'wait', 't3', '--json')
  assert.equal(ok.code, 0)
  assert.equal(JSON.parse(ok.stdout).result.status, 'ok')
  list = cli(w, 'list')
  assert.match(list.stdout, /^t1-cache {2}done {6}canceled {3}-1 {4}1m31s {5}2026-09-25T10:00:00\.000Z$/m)
  assert.match(list.stdout, /^t3 {8}done {6}ok {9}0 {5}1m31s/m)
})
